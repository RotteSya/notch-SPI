// Generated Swift and browser modules are checked in; neither platform needs the other toolchain.
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { stripTypeScriptTypes } from "node:module";
import { autoDefaults } from "../../shared/protocol/auto-session.mjs";
const root = fileURLToPath(new URL("../../", import.meta.url));
const read = (name) =>
  JSON.parse(fs.readFileSync(path.join(root, "shared", name), "utf8"));
const product = read("product.json"),
  prompts = read("prompts.json");
const version = Object.fromEntries(
  fs
    .readFileSync(path.join(root, "VERSION.env"), "utf8")
    .trim()
    .split("\n")
    .map((x) => x.split("=")),
);
const number = (n) => (Number.isInteger(n) ? `${n}.0` : String(n));
const swift = `// Generated by scripts/cross-platform/generate.mjs. Edit shared/ instead.\nimport Foundation\n\nenum SharedProduct {\n    static let personalityMaxAge: TimeInterval = ${number(product.personalitySession.maxAgeSeconds)}\n    static let personalityMaxRecords = ${product.personalitySession.maxRecords}\n    static let personalityMaxContextBytes = ${product.personalitySession.maxContextBytes}\n    static let captureLimit = ${product.capture.limit}\n    static let submitDelay: TimeInterval = ${number(product.capture.submitDelay)}\n    static let reasoningEfforts = ${JSON.stringify(product.reasoningEfforts)}\n    static let autoCaps = ${JSON.stringify(product.autoCaps)}\n    static let defaultAutoCap = ${product.defaultAutoCap}\n    static let motionDuration: Double = ${number(product.motion.duration)}\n    static let springDecay: Double = ${number(product.motion.springDecay)}\n    static let springFrequency: Double = ${number(product.motion.springFrequency)}\n    static let closeDecay: Double = ${number(product.motion.closeDecay)}\n    static let cardWidth: Double = ${number(product.layout.cardWidth)}\n    static let contractVersion = ${JSON.stringify(product.contractVersion)}\n    private static let templates: [String: String] = [\n${Object.entries(
  prompts,
)
  .map(
    ([k, v]) =>
      `        ${JSON.stringify(k)}: ${JSON.stringify(v).replace(/\\u([0-9a-fA-F]{4})/g, "\\u{$1}")}`,
  )
  .join(
    ",\n",
  )}\n    ]\n    static func prompt(_ key: String, values: [String: String] = [:]) -> String {\n        let template = templates[key]!\n        // Replace placeholders in the template only; user values are never re-expanded.\n        let regex = try! NSRegularExpression(pattern: #"\\{\\{(\\w+)\\}\\}"#)\n        var result = template\n        for match in regex.matches(in: template, range: NSRange(template.startIndex..., in: template)).reversed() {\n            let name = (template as NSString).substring(with: match.range(at: 1))\n            if let value = values[name], let range = Range(match.range, in: result) { result.replaceSubrange(range, with: value) }\n        }\n        return result\n    }\n}\n`;
const outputs = {
  "Sources/NotchSPI/Shared/SharedProduct.generated.swift": swift,
  "desktop/generated/product.mjs": `// Generated. Edit shared/ instead.\nexport const product = ${JSON.stringify(product, null, 2)};\nexport const templates = ${JSON.stringify(prompts, null, 2)};\nexport const version = ${JSON.stringify(version)};\n`,
};
const objective = stripTypeScriptTypes(
  fs.readFileSync(path.join(root, "server/src/objective-result.ts"), "utf8"),
);
outputs["desktop/generated/objective.mjs"] =
  "// Generated from server/src/objective-result.ts.\n" +
  objective.replace(
    "Buffer.byteLength(payload, 'utf8')",
    "new TextEncoder().encode(payload).length",
  ).replace(/[ \t]+$/gm, "");
const jsCore = objective
  .replaceAll("export ", "")
  .replace(
    "Buffer.byteLength(payload, 'utf8')",
    "unescape(encodeURIComponent(payload)).length",
  );
outputs["Sources/NotchSPI/Shared/SharedObjective.generated.swift"] =
  `// Generated from server/src/objective-result.ts; executed by JavaScriptCore on macOS.\nimport Foundation\nimport JavaScriptCore\n\nenum SharedObjective {\n    private static let source = ${JSON.stringify(jsCore)}\n    static func compose(_ raw: String, enabled: Bool) -> ObjectiveResultComposition {\n        guard let context = JSContext() else { return failure }\n        context.evaluateScript(source)\n        guard context.exception == nil, let value = context.objectForKeyedSubscript("composeObjectiveResult")?.call(withArguments: [raw, enabled]),\n              context.exception == nil, let object = value.toDictionary(),\n              let data = try? JSONSerialization.data(withJSONObject: object),\n              let result = try? JSONDecoder().decode(ObjectiveResultComposition.self, from: data) else { return failure }\n        return result\n    }\n    private static var failure: ObjectiveResultComposition {\n        .init(visibleText: "", finalAnswer: nil, result: nil, state: nil, parserPath: .none, violations: [.invalidJSON, .missingUsableResult])\n    }\n}\n`;
const personality = fs.readFileSync(path.join(root, "shared/protocol/personality.mjs"), "utf8");
outputs["desktop/generated/personality.mjs"] = "// Generated from shared/protocol/personality.mjs.\n" + personality;
outputs["Sources/NotchSPI/Shared/SharedPersonalitySource.generated.swift"] =
  `// Generated from shared/protocol/personality.mjs.\nimport Foundation\nenum SharedPersonalitySource { static let javascript = ${JSON.stringify(personality.replaceAll("export ", ""))} }\n`;
const autoSource = fs.readFileSync(path.join(root, "shared/protocol/auto-session.mjs"), "utf8");
outputs["desktop/generated/auto-session.mjs"] = "// Generated from shared/protocol/auto-session.mjs.\n" + autoSource;
outputs["Sources/NotchSPI/Shared/SharedAutoSource.generated.swift"] =
  `// Generated from shared/protocol/auto-session.mjs.\nimport Foundation\nenum SharedAutoSource {\n    static let javascript = ${JSON.stringify(autoSource.replaceAll("export ", ""))}\n${Object.entries(autoDefaults).map(([key, value]) => `    static let ${key} = ${value}`).join("\n")}\n}\n`;
// UI sources are local, pinned and copied byte-for-byte into the desktop package.
const visual = [
  "ghost-engine",
  "ghost-motion",
  "flight",
  "capture",
  "reading",
  "onboarding",
];
for (const name of [...visual, "ghost"])
  outputs[`desktop/generated/ui/${name}.mjs`] = fs.readFileSync(
    path.join(root, `shared/ui/${name}.mjs`),
    "utf8",
  );
for (const file of fs.readdirSync(
  path.join(root, "shared/ui/vendor/bot-avatars"),
)) {
  const source = fs.readFileSync(
    path.join(root, "shared/ui/vendor/bot-avatars", file),
    "utf8",
  );
  outputs[
    `desktop/generated/ui/vendor/bot-avatars/${file.replace(/\.ts$/, ".mjs")}`
  ] = file.endsWith(".ts")
    ? stripTypeScriptTypes(source, { mode: "transform" }).replace(
        /from (['"])(\.\/[^'"]+)\1/g,
        "from $1$2.mjs$1",
      )
    : source;
}
const visualJS = visual
  .map((name) =>
    fs
      .readFileSync(path.join(root, `shared/ui/${name}.mjs`), "utf8")
      .replaceAll("export ", "")
      .replace(/^import .*$/gm, ""),
  )
  .join("\n");
outputs["Sources/NotchSPI/Shared/SharedVisualSource.generated.swift"] =
  `// Generated shared UI. Edit shared/ui instead.\nimport Foundation\nenum SharedVisualSource { static let javascript = ${JSON.stringify(visualJS)} }\n`;
for (const [name, content] of Object.entries(outputs)) {
  const file = path.join(root, name);
  if (process.argv.includes("--check")) {
    if (!fs.existsSync(file) || fs.readFileSync(file, "utf8") !== content)
      throw new Error(`Stale generated source: ${name}`);
  } else {
    fs.mkdirSync(path.dirname(file), { recursive: true });
    fs.writeFileSync(file, content);
  }
}
console.log("Shared product sources are synchronized.");
